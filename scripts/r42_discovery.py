# -*- coding: utf-8 -*-
"""
R42 ENGINE — «ОБНАРУЖЕНИЕ: минимальная наблюдаемая конфигурация рентного механизма».

Метод: 6 реальных документированных случаев + 2 отрицательных контроля + 7 реальных
природных экспериментов (история провела атаки сама). Формализация ПОСЛЕ наблюдения.

Проверки:
  CHK1 присутствие: каждая положительная позиция содержит ВСЕ 6 наблюдаемых элементов
       (+ наблюдаемые поток/цена/петля/бесплатное размещение);
  CHK2 отсутствие: каждый контроль ДОКУМЕНТИРОВАННО лишён несущих элементов и имеет
       наблюдённый исход без ренты/с рассеянием;
  CHK3 природные эксперименты: каждый выбитый элемент опирается на реальные операции
       своего случая и наблюдённый исход;
  CHK4 антиподгонка: ни одно описание операции не содержит токенов формального словаря
       проекта (машинный запрет «придуманная модель → поиск подтверждений»);
  CHK5 уверенность: несущие элементы в каждом случае подтверждены не ниже MED.
"""
import json, sys, os

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from r42_data import (POSITIVE, CONTROLS, KNOCKOUTS, FORMAL_TOKENS, CONF_ORDER)

OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "r42_results.json")
COMPONENTS = ["K1", "K2", "K3", "K4", "K5", "K6"]
OBSERVED   = ["FLOW", "PRICE", "LOOP", "FREE"]
fails = []
report = {"CHK1": {}, "CHK2": {}, "CHK3": [], "CHK4": None, "CHK5": {}}

def tags_of(ops):
    t = {}
    for oid, y, d, doc, src, conf, tags in ops:
        for tag in tags:
            t.setdefault(tag, []).append((oid, conf))
    return t

def fmt_case(cid):
    return {"NYC_MEDALLION": "НЙК-медальоны", "ISLAND_ITQ": "Исландия-ITQ",
            "RF_1995": "РФ-1995", "NJ_LIQUOR": "Нью-Джерси-лицензии",
            "HK_TAXI": "Гонконг-такси", "NZ_ITQ": "НЗ-QMS",
            "LONDON_KNOWLEDGE": "Лондон-knowledge", "OPEN_ACCESS_HERRING": "открытый-доступ"}.get(cid, cid)

print("=" * 100)
print("R42  ОБНАРУЖЕНИЕ: минимальная наблюдаемая конфигурация, которая РЕАЛЬНО")
print("     производит, извлекает и воспроизводит рентный поток")
print("=" * 100)

# ---------- CHK4 антиподгонка (запускаю ПЕРВОЙ: словарь модели запрещён в наблюдении) ----------
contam = []
for group in (POSITIVE, CONTROLS):
    for case, ops in group.items():
        for oid, y, d, doc, src, conf, tags in ops:
            for tok in FORMAL_TOKENS:
                if tok in d:
                    contam.append((case, oid, tok))
report["CHK4"] = {"contaminations": contam}
if contam:
    fails.append(f"CHK4: формальный словарь просочился в наблюдение: {contam}")
print(f"\n[CHK4] Антиподгонка: описания операций чисты от формального словаря проекта "
      f"({len(contam)} вкраплений в {sum(len(o) for o in list(POSITIVE.values())+list(CONTROLS.values()))} операциях) "
      f"{'PASS' if not contam else 'FAIL'}")

# ---------- CHK1 присутствие ----------
print("\n[CHK1] Присутствие всех 6 элементов + наблюдаемых поток/цена/петля/бесплатное размещение:")
matrix = {}
for case, ops in POSITIVE.items():
    t = tags_of(ops)
    row = {}
    for k in COMPONENTS + OBSERVED:
        found = t.get(k, [])
        best = max((CONF_ORDER[c] for _, c in found), default=0)
        row[k] = {"present": bool(found), "ops": [o for o, _ in found], "best_conf": best}
        if not found:
            fails.append(f"CHK1: {case}: элемент {k} НЕ НАБЛЮЖДАЕТСЯ")
    # несущие элементы должны иметь уверенность >= MED
    weak = [k for k in COMPONENTS if row[k]["present"] and row[k]["best_conf"] < CONF_ORDER["MED"]]
    if weak:
        fails.append(f"CHK5: {case}: несущие элементы {weak} подтверждены ниже MED")
    matrix[case] = row
    missing = [k for k in COMPONENTS + OBSERVED if not row[k]["present"]]
    print(f"  {fmt_case(case):<22} " + " ".join(
        f"{k}:{'+' if row[k]['present'] else '−'}" for k in COMPONENTS + OBSERVED)
        + ("" if not missing else f"   ОТСУТСТВУЕТ: {missing}"))
report["CHK1"] = matrix

# ---------- CHK2 отсутствие в контролях ----------
print("\n[CHK2] Отрицательные контроля (отсутствие — тоже наблюдение):")
ctl_req = {
    "LONDON_KNOWLEDGE":    (["LACK:K1", "LACK:K3", "OUT:NORENT"], "есть исключение, НЕТ численного предела и отделимости → цены места нет"),
    "OPEN_ACCESS_HERRING": (["LACK:K1", "LACK:K2", "LACK:K3", "LACK:K6", "OUT:DISSIP"], "нет ничего → рента рассеялась в коллапсе"),
}
for case, ops in CONTROLS.items():
    t = tags_of(ops)
    req, why = ctl_req[case]
    have = {r: any(r in tg for tg in t) for r in req}
    for r in req:
        if not have[r]:
            fails.append(f"CHK2: контроль {case}: не документировано {r}")
    print(f"  {fmt_case(case):<22} документировано: {', '.join(req)} → PASS" if all(have.values())
          else f"  {fmt_case(case):<22} FAIL: {[r for r in req if not have[r]]}")
    report["CHK2"][case] = {r: have[r] for r in req}

# ---------- CHK3 природные эксперименты ----------
print("\n[CHK3] Реальные природные эксперименты (история выбивала/добавляла элементы сама):")
all_ids = {case: {op[0] for op in ops} for group in (POSITIVE, CONTROLS) for case, ops in group.items()}
for kid, case, ops_used, what, outcome, verdict in KNOCKOUTS:
    if case not in all_ids:
        fails.append(f"CHK3: {kid}: неизвестный случай {case}"); continue
    bad = [o for o in ops_used if o not in all_ids[case]]
    if bad:
        fails.append(f"CHK3: {kid}: операции {bad} не существуют в {case}")
    report["CHK3"].append({"id": kid, "case": case, "ops": ops_used, "what": what,
                           "outcome": outcome, "verdict": verdict})
    print(f"  {kid} [{fmt_case(case):<20}] {what}")
    print(f"      исход: {outcome}")
    print(f"      → {verdict}")

# ---------- вывод: обнаруженная конфигурация ----------
ok = not fails
print("\n" + "=" * 100)
print("ВЫВОД R42 (формализация ПОСЛЕ наблюдения)")
print("=" * 100)
print("""
ОБНАРУЖЕННАЯ КОНФИГУРАЦИЯ — 6 наблюдаемых элементов + 1 несущий результат:

  K1  ПРЕДЕЛ МНОЖЕСТВА НОСИТЕЛЕЙ  — норма (закон/указ/правило аукциона), замыкающая
      множество держателей: ЧИСЛОМ (12 187; ~15 000; 1/3000; TAC) или структурным
      признаком (закрытые аукционы, «вариант 2»).
  K6  РЕЕСТР НОСИТЕЛЕЙ            — учёт, фиксирующий, КТО ИМЕННО держит место
      (медальонный реестр TLC; реестр долей Директората; реестры акционеров; ABC; ТД Гонконга).
  K2  ДЕЙСТВУЮЩЕЕ ИСКЛЮЧЕНИЕ      — аппарат, применяемый к неполучившим место
      (штрафы/изъятия; журналы+весовые+инспекторы; ЧОП и захваченные суды; ABC; полиция).
  K3  ОТДЕЛИМОСТЬ МЕСТА ОТ ЛИЦА   — место передаётся/арендуется независимо от труда держателя.
  K4  ФИНАНСОВОЕ ПОГРУЖЕНИЕ       — место принимается как залог, обращается как капитал.
  K5  ПОЛИТИЧЕСКОЕ ВОСПРОИЗВЕДЕНИЕ АКТА — организованное влияние держателей на сохранение нормы
      (лобби; конституционная защита; админресурс; иски против платформ).

  НЕСУЩИЙ РЕЗУЛЬТАТ: ПОТОК = регулярный сбор держателя места за цикл, остающийся после
  издержек исключения. Поток берёт начало в ПРИВЕДЕНИИ НОРМЫ В ИСПОЛНЕНИЕ, а не в физическом факте.

ПРОВОДКА (наблюдённая петля, одинакова во всех 6 случаях):

   АКТ(K1) ──► РЕЕСТР(K6) ──► ИСКЛЮЧЕНИЕ(K2) ──► ПОТОК держателю
      │ первичное размещение ≈ БЕСПЛАТНО (FREE во всех 6)         │
      │                                                          │ отделимость(K3)
      │                                                          ▼
      │                              РЫНОК МЕСТА ──► КАПИТАЛИЗАЦИЯ(K4: залог, цена)
      │                                                          │
      └◄── ПОЛИТИЧЕСКОЕ ВОСПРОИЗВЕДЕНИЕ АКТА(K5) ◄── организованные держатели

  Шоковой канал: ЗАМЕСТИТЕЛЬ входит вне досягаемости исключения (K2) → при незакрытии
  рушатся цена и частично поток (наблюдено: NYC 2011—22; Гонконг 2018—24). Норма закона
  при этом не менялась — обрушилось ИСПОЛНЕНИЕ, не текст.

ТРЁХСЛОЙНАЯ СТРУКТУРА (элементы группируются по наблюдённой нагрузке):

  СЛОЙ F (поток):        K1 + K6 + K2   — минимум, без которого потока нет
                                        (контроль «открытый доступ»: рассеяние);
  СЛОЙ P (капитализация): K3 + K4        — без него поток есть, ЦЕНЫ МЕСТА нет
                                        (контроль «Лондон»: вход затруднён на годы,
                                         но места-капитала не существует);
  СЛОЙ W (воспроизводство): K5 (+обновление K1) — без него петля не переживает
                                        смены эпох (в РФ-2000-е держатель-государство
                                        интернализовал K5 — второй цикл состоялся).
""")

if ok:
    print(f"ИТОГ R42: ВСЕ ПРОВЕРКИ PASS — CHK1 (6 случаев × 6 элементов), CHK2 (2 контроля), "
          f"CHK3 ({len(KNOCKOUTS)} реальных экспериментов), CHK4 (антиподгонка), CHK5 (уверенность ≥MED).\n"
          "СТАТУС: КОНФИГУРАЦИЯ НАБЛЮДЕНА, НЕ СПРОЕКТИРОВАНА. Словарь модели применён только "
          "в сведение (ниже), в фазе наблюдения не использовался.")
else:
    print("ИТОГ R42: FAIL — обнаружены дефекты:")
    for f in fails:
        print("  ✗", f)

# ---------- сведение с кандидатами (отдельная фаза — после наблюдения) ----------
print("\n" + "-" * 100)
print("СВЕДЕНИЕ С КАНДИДАТАМИ ПРОЕКТА (статусы обновлены ТОЛЬКО там, где наблюдение говорило):")
print("""
  R20 «R>0 ⟺ вход закрыт»        ПОДТВЕРЖДЁН И УЖЕСТОЧЁН: поток требует замкнутости
                                 множества носителей ЧИСЛОМ/ПРИЗНАКОМ; качественный
                                 барьер (Лондон) потока места не производит.
  R25 «цена входа ≈ PV потока»   ОГРАНИЧЕН СЛОЕМ P: верно при K3+K4; поток существует
                                 без цены места (РФ 1992—94; Лондон).
  R30 «P_entry ∉ минимальной
       конфигурации»             ПОДТВЕРЖДЁН: минимум потока = K1+K6+K2, без K3/K4.
  R31 «C_gen vs C_trans»         ПОДТВЕРЖДЁН: K6+K2 — наблюдаемый класс издержек передачи
                                 (бюджеты TLC/Директората, ЧОП, рейдерские войны).
  R32 «передаётся пакет, выгода
       регенерирует»             ПОДТВЕРЖДЁН СИСТЕМНО: между периодами физически переходит
                                 пакет «акт+реестр+правило размещения+аппарат» (медальоны
                                 85+ лет; QMS 35+ лет; номенклатура через смену эпох).
  S (редкость как сомножитель)   НАБЛЮДЕНА как конкретные числа пределов (K1).
  Φ {DORMANT, ACTIVE,
     TRANSFER, SUBSTITUTE}       НАБЛЮДЕНО: SUBSTITUTE = платформы (NYC 2011—15, HK 2018+),
                                 TRANSFER = каждая сделка, DORMANT = пандемийный провал.
  З1…З14, R34, R41               ЭТОЙ ЗАДАЧЕЙ НЕ ТЕСТИРОВАЛИСЬ — статус «кандидат» сохраняется.
""")

print("НОВЫЕ ОТКРЫТИЯ (в наблюдении их не было в ядре проекта):")
print("""
  Д1  Первая опора механизма — НОРМАТИВНЫЙ ТЕКСТ С СИЛОЙ. Во всех 6 случаях цепочка
      начинается актом, а не физическим фактом. Рента производится приведением нормы
      в исполнение на экономике, а не собирается с природы.
  Д2  ИЗГОТОВЛЕНИЕ МЕСТА ВСЕГДА ≈ БЕСПЛАТНО ДЛЯ БУДУЩИХ ДЕРЖАТЕЛЕЙ (grandfathering,
      номинальные ваучеры, залоговые цены в долю стоимости, выдача за номинал).
      Создание ренты отделено от извлечения: редкость сначала ОБЪЯВЛЯЕТСЯ, потом
      монетизируется ниже по цепочке.
  Д3  ТРЁХСЛОЙНОСТЬ: поток (K1,K6,K2) / капитализация (K3,K4) / воспроизводство (K5)
      — прежнее ядро G=(B,E,C,T) отображается на СЛОИ, а не на элементы; слои можно
      наблюдать по отдельности (РФ 1992—94: F без P; Лондон: барьер без P; NYC 2020—22:
      F частично живёт при разрушенном P).
  Д4  КАЧЕСТВЕННЫЙ БАРЬЕР НЕ РАВЕН ПРЕДЕЛУ МНОЖЕСТВА: «вход затруднён» (экзамен, 2—4 года)
      не производит ренты места; производит только замыкание МНОЖЕСТВА.
  Д5  РЕЕСТР — НЕСУЩИЙ, А НЕ ТЕХНИЧЕСКИЙ: оспариваемый реестр (РФ) вздувает издержки
      исключения и рассеивает часть потока в защиту места.
""")

print("UNKNOWN (остаётся открытым, честно):")
print("""
  U1  Надбавка лондонских водителей за редкость навыка — квази-рента без места? (данных нет)
  U2  Масштаб потока РФ 1990-х (офшорный вывоз) — LOW, нужен реестровый источник.
  U3  Контрфактический налог на ренту в Исландии (усечён 2012, эффектов не оценено).
  U4  Необходим ли K5 как отдельный элемент или интернализуется держателем-государством
      (РФ-2000-е — единственный наблюдённый случай, n=1).
  U5  Траектория Гонконга после 2024 (регуляторное решение по платформам) — не завершена.
""")

report["verdict"] = "PASS" if ok else "FAIL"
report["fails"] = fails
with open(OUT_PATH, "w", encoding="utf-8") as f:
    json.dump(report, f, ensure_ascii=False, indent=1)
print(f"\nАртефакт: {OUT_PATH}")
sys.exit(0 if ok else 1)
