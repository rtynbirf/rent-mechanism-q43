# ЗАДАЧА 7 "ДОЖИМ": эмпирическая развёртка горизонтов H1(cc)/H2(eta-drift)/H5(DSR)/H3(матрица A/B)
import math

def card(tid, inp, method, expected, actual, status, lim="-"):
    print(f"\n=== {tid} ===\nINPUT:    {inp}\nMETHOD:   {method}\nEXPECTED: {expected}\nACTUAL:   {actual}\nSTATUS:   {status}")
    if lim != "-": print(f"LIMITS:   {lim}")

R, EPS, H, DA, C = 0.35, 0.5, 0.3, 0.05, 0.5
def attractor(phi, steps=800, eps=EPS, S0=0.9, A0=0.4):
    S, A = S0, A0
    for _ in range(steps):
        E = eps * S * A / (H + A) if (S > 0 and A > 0) else 0.0
        S = max(0.0, S + R * S * (1 - S) - E)
        A = max(0.0, (1 - DA) * A + phi * E - C * A * A)
        if A <= 1e-9: return S, 0.0
    return S, A

# T-D1: cc-эмпирика -> phi-калибровка
def td1():
    S9, A9 = attractor(0.9); S3, A3 = attractor(0.3); S1, A1 = attractor(0.1)
    card("T-D1_cc_empirics_calibration",
         "эмп. якоря: Fagereng et al. 2019 (NBER w26588, норв. админ-данные): сбережения богатых из капитальных ПРИРОСТОВ ~100%; ФГМП Econometrica 2020: разброс доходностей 10->90 перц. +18 п.п., персистентность, межгенерационная корреляция",
         "phi=1-cc; модельный свип phi по уровням аппарата A*; сравнение эмпирического phi_top с порогом phi_min=0.300 (T-F1)",
         "phi_top >> phi_min -> там, где ренту захватывают верхние классы, петля в самоподдерживающемся режиме; cc-порог работает только для средних/нижних",
         f"A*(phi=0.9)={A9:.3f}, A*(0.3)={A3:.3f} (=канонический), A*(0.1)={A1:.3f}; эмп. phi_top~0.9-1.0 (приросты) -> запас над phi_min=0.300 x3",
         "SUPPORTED (модель) / SOURCE_CLAIM (эмп.: приросты≠потоки дохода)",
         "домен: Норвегия; капитальные gains ≠ рентные потоки; для медийных классов INSUFFICIENT_DATA")
    return A9, A3, A1

# T-D2: eta-drift по Knoll et al. 2017 (уточнённые якоря вместо T-F5)
def td2():
    kappa, w = 0.301, 0.123
    s_1900, s_2010 = 0.20, 0.40   # Knoll: ~20% на рубеже XX в. -> ~40% к 2010-м (США)
    r1900, r2010 = kappa * w * s_1900, kappa * w * s_2010
    ann = (r2010 / r1900) ** (1 / 110) - 1
    card("T-D2_eta_drift_knoll",
         "kappa=30.1% (Tax Foundation 1929-2023 стаб.); housing=12.3% Y (NAHB Q3'25); доля земли в стоимости жилья США: 20%->40% за ~110 лет (Knoll-Schularick-Steeger 2017: 'roughly doubled over the twentieth century'); >80% роста цен 1950-2012 = земля",
         "R_land(t)=kappa*s_land(t)*w*Y(t); дрейф доли ренты в Y при фикс. D (узкая граница)",
         "рентный поток удваивается внутри стабильной факторной доли; годовой дрейф доли ~0.7%/год",
         f"земельная рента: {r1900*100:.2f}% Y -> {r2010*100:.2f}% Y (x{r2010/r1900:.2f}); годовой дрейф доли = {ann*100:.2f}%/год при kappa,w=const",
         "DERIVED (на опубликованных долях)",
         "w исторически менялась (INSUFFICIENT_DATA); 80%-атрибуция относится к ЦЕНАМ, не к потокам; страна: США")
    return r1900, r2010

# T-D3: DSR как eta (поток D->R домохозяйств) -> запас до границы
def td3():
    tdsp, dpi_gdp_lo, dpi_gdp_hi = 0.1116, 0.68, 0.74
    eta_lo, eta_hi = tdsp * dpi_gdp_lo, tdsp * dpi_gdp_hi
    model_E_over_S = 0.08687 / 0.45744
    margin = model_E_over_S / (eta_hi / 1.0)  # во сколько раз модельная интенсивность выше эмп. потолка
    card("T-D3_dsr_eta_mapping",
         "FRED TDSP Q1'26=11.16% располагаемого дохода (корпус); DPI/GDP США ~0.68-0.74 (ASSUMED); модель: E*/S*=0.19",
         "eta_ceiling = TDSP x DPI/Y -> сравнение интенсивности изъятия с каноническим аттрактором",
         "домохозяйственный D->R канал работает в разы слабее модельного эпс -> сектор в глубоком режиме выживания, граница ε<r далека",
         f"eta_ceiling={eta_lo*100:.1f}-{eta_hi*100:.1f}% Y; модельная интенсивность 19% базы; запас по интенсивности ~x{margin:.1f} (2.4-2.6)",
         "DERIVED (калибровочная привязка, не оценка риска)",
         "TDSP = ВСЕ обязательные платежи (incl. тело в amortиз.), рентная часть (процент) меньше — INSUFFICIENT_DATA; R->D сторона: MERS +3.1-3.4%/год (Gao et al.)")
    return eta_lo, eta_hi

# T-D4: матрица тип редкости x класс записи -> гибридная платформа
def td4():
    print("\n=== T-D4_matrix_AB_record (запись доменами корпуса) ===")
    print("ЗЕМЛЯ:      тип A | сброс структурно невозможен (поток переживает любое правило)")
    print("ЛИЦЕНЗИЯ:   тип B | сброс экзогенный (акт воли: DMA, PSR, отмена)")
    print("ПАТЕНТ:     тип B | сброс ЭНДОГЕННЫЙ по расписанию (~20 лет; продления сделками: Rinvoq->2037)")
    print("ДОЛГ:       гибрид| сброс только институциональный B(t) (амнистия/haircut) — рыночный шок -45% не работает (T-F4)")
    print("ПЛАТФОРМА:  гибрид| beta=доля редкости, сконструированная правилом доступа; (1-beta)=сетевые эффекты (тип A)")
    betas, rows = [0.0, 0.25, 0.5, 0.75, 1.0], []
    for b in betas:
        # после снятия правила доступа остаётся (1-b)*eps потока
        S, A = attractor(0.3, eps=EPS * (1 - b))
        rows.append((b, EPS * (1 - b), A))
    out = "; ".join(f"b={b:.2f}:eps_eff={e:.2f},A={a:.4f}" for b, e, a in rows)
    card("T-D4_matrix_AB_record",
         "гибридная платформа: beta - сконструированная правилом доля редкости; пост-сброс eps_eff=(1-b)*eps",
         "двухсекторная модель, eps-эффективная после снятия правила; phi=0.3",
         "поток переживает сброс частично и убывает по beta; при beta=1 - полный коллапс (тип B)",
         out,
         "MODEL (типология доменов корпуса)",
         "beta по реальным платформам не измерена — INSUFFICIENT_DATA; кандидаты измерения: уход сделок после смены комиссии (+3.2/+4.4 п.п.)")

if __name__ == "__main__":
    print("ДОЖИМ: эмпирическая развёртка H1/H2/H5/H3")
    td1(); td2(); td3(); td4()
