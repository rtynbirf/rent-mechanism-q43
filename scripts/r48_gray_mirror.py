R["cases"] = CASES

# CHK1 — закон серого зеркала: живая рента при K1=1∧K2=1 ⟹ (легальная цена>0) ∨ (тень>0)
gm = [c for c in CASES if c["rent_alive"] and c["K1"] == 1 and c["K2"] == 1]
ok1 = all((c["legal_price"] > 0) or (c["shadow"] > 0) for c in gm)
check("CHK1", f"Серое зеркало на {len(gm)} живых K1K2-кейсах: цена либо легальна, либо в тени; никогда нигде не ноль", ok1)

# CHK2 — симметрия негативного контроля: K1=0 ⟹ цена места = 0 В ОБОИХ режимах
neg = [c for c in CASES if c["K1"] == 0]
ok2 = all(c["legal_price"] == 0 and c["shadow"] == 0 for c in neg)
check("CHK2", f"Без капа множества цены нет ни легально, ни в тени ({[c['id'] for c in neg]})", ok2,
      "джитни 1915: закрытие удушением (bond $2–10k, маршруты, тариф) не успело капитализировать место")

# CHK3 — диагностическое правило: вывод «нет цены ⟹ нет ренты» валиден только в легальном режиме
# (т.е. при открытой легальной капитализации и известном K1). В теневом режиме — диагностика по потоку.
legal_regime_alive = [c for c in gm if c["legal_price"] > 0]
shadow_regime_alive = [c for c in gm if c["legal_price"] == 0 and c["shadow"] > 0]
ok3 = len(legal_regime_alive) >= 1 and len(shadow_regime_alive) >= 1
check("CHK3", f"Оба режима реализованы: легальный {[c['id'] for c in legal_regime_alive]}, теневой {[c['id'] for c in shadow_regime_alive]}; правило диагностики отделимо", ok3)

# CHK4 — капитализационный мультипликатор СССР: 500k руб / (2800 руб/мес × 12) ≈ годы дохода
u = next(c for c in CASES if c["id"] == "USSR-nomenklatura")
ok4 = 10.0 <= u["norm"] <= 20.0  # класс капитализационных мультипликаторов (не «подарок», не месячный оклад)
check("CHK4", f"Теневая цена номенклатуры = капитализация ~{u['norm']:.1f} лет дохода (мультипликаторный класс)", ok4)

# CHK5 — калибровочная правка FR6 (r47d): дно NYC = плато PM $70–75k (ноя 2020 – июль 2021),
# май 2021 RAW = $80k; пик $1.0–1.3M ⟹ ΔV ∈ [−0.94, −0.89]; F ≈ −0.4…−0.5. Вывод |ΔP|>|ΔF| устойчив.
peaks = [1.0e6, 1.3e6]; bottoms = [70e3, 75e3, 80e3]
dv = [1.0 - b / p for p in peaks for b in bottoms]
